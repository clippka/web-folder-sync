#!/usr/bin/env node
// Aggregates harness result files into docs/feasibility/compatibility-matrix.md.
//   node tools/report.mjs [--results harness/results] [--out docs/feasibility/compatibility-matrix.md]
// Results recorded against OPFS (headless smoke) are ignored: they are not evidence.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';

const here = path.dirname(fileURLToPath(import.meta.url));
const { values } = parseArgs({ options: { results: { type: 'string', default: path.join(here, '..', 'results') }, out: { type: 'string', default: path.join(here, '..', '..', 'docs', 'feasibility', 'compatibility-matrix.md') } } });

const COMBOS = ['windows/chrome', 'windows/edge', 'linux/chrome', 'linux/edge', 'macos/chrome', 'macos/edge'];
const osKey = (p = '') => { p = p.toLowerCase(); return p.includes('win') ? 'windows' : p.includes('mac') ? 'macos' : p.includes('linux') || p.includes('cros') ? 'linux' : p || 'unknown'; };
const RANK = { error: 5, fail: 4, skipped: 1, info: 2, pass: 3 }; // worst-wins except pass beats info/skipped
const worst = (a, b) => (!a ? b : (a === 'error' || a === 'fail') ? a : (b === 'error' || b === 'fail') ? b : RANK[a] >= RANK[b] ? a : b);

const files = fs.existsSync(values.results) ? fs.readdirSync(values.results).filter((f) => f.endsWith('.json')) : [];
const runs = []; // {combo, env, scenario, results, manual, file}
for (const f of files) {
  let j;
  try { j = JSON.parse(fs.readFileSync(path.join(values.results, f), 'utf8')); } catch { console.warn(`skipping unreadable ${f}`); continue; }
  const combo = `${osKey(j.env?.platform)}/${j.env?.browser}`;
  runs.push({ combo, env: j.env, scenario: j.scenario, results: j.results ?? {}, history: j.history ?? [], manual: j.manual ?? {}, file: f });
}

// The page keeps a cumulative history, so later saves repeat earlier runs: drop duplicates (same test id and timestamp).
// A history entry carrying `invalid: "<reason>"` (added by hand when a run was a harness or operator mistake) is
// excluded from every table and listed under "Excluded runs" instead of being silently deleted.
const excluded = [];
const seen = new Set();
for (const r of runs) {
  r.history = r.history.filter((h) => {
    const key = `${r.combo}|${h.id}|${h.at}`;
    if (h.at && seen.has(key)) return false;
    seen.add(key);
    if (h.invalid) { excluded.push(`- **${r.combo}** ${h.id} (${h.scenario || '—'}, ${h.at}): ${h.invalid}`); return false; }
    return true;
  });
}

const cell = {}; // [testId][combo] -> {status, n}
const testIds = new Set(); const manualIds = new Set(); const manualCell = {};
const versions = {};
for (const r of runs) {
  if (COMBOS.includes(r.combo)) (versions[r.combo] ??= new Set()).add(`${r.env.browserVersion ?? '?'} / ${r.env.platform} ${r.env.platformVersion ?? ''}`.trim());
  for (const h of r.history.length ? r.history : Object.values(r.results)) {
    if (h.rootKind === 'opfs') continue;
    testIds.add(h.id);
    const c = ((cell[h.id] ??= {})[r.combo] ??= { status: null, n: 0 });
    c.status = worst(c.status, h.status); c.n++;
  }
  for (const [id, m] of Object.entries(r.manual)) {
    if (!m.result) continue;
    manualIds.add(id);
    const c = ((manualCell[id] ??= {})[r.combo] ??= { status: null });
    c.status = c.status && c.status !== m.result ? 'mixed' : m.result;
  }
}

const sym = (c) => (c ? `${{ pass: '✅', fail: '❌', error: '❌', info: 'ℹ️', skipped: '⏭️' }[c.status] ?? c.status} ${c.status}${c.n > 1 ? ` (${c.n} runs)` : ''}` : '—');
const L = [];
L.push('# Browser compatibility matrix', '', `Generated by \`harness/tools/report.mjs\` from ${files.length} result file(s). Do not edit by hand; re-run the tool.`, '');
const covered = COMBOS.filter((c) => Object.values(cell).some((row) => row[c]));
L.push(`**Combinations with evidence: ${covered.length} of 6** (${covered.join(', ') || 'none'}). Missing: ${COMBOS.filter((c) => !covered.includes(c)).join(', ') || 'none'}.`, '');
L.push('## Versions tested', '', '| Combination | Browser / OS versions |', '|---|---|');
for (const c of COMBOS) L.push(`| ${c} | ${versions[c] ? [...versions[c]].join('<br>') : '—'} |`);
L.push('', '## Automated tests', '', `| Test | ${COMBOS.join(' | ')} |`, `|---|${COMBOS.map(() => '---').join('|')}|`);
for (const id of [...testIds].sort()) L.push(`| ${id} | ${COMBOS.map((c) => sym(cell[id]?.[c])).join(' | ')} |`);
L.push('', '## Manual scenarios', '', `| Scenario | ${COMBOS.join(' | ')} |`, `|---|${COMBOS.map(() => '---').join('|')}|`);
for (const id of [...manualIds].sort()) L.push(`| ${id} | ${COMBOS.map((c) => manualCell[id]?.[c]?.status ?? '—').join(' | ')} |`);

L.push('', '## Performance runs', '', '| Combination | Scenario | Files | Included MiB | Enumeration ms | Total ms | First progress ms | Files/s | MiB/s | Heap growth MiB | Max main-thread lag ms | Cancel ms | Config |', '|---|---|---|---|---|---|---|---|---|---|---|---|---|');
for (const r of runs) for (const h of r.history) {
  if (h.id !== 'perf' || h.rootKind === 'opfs' || !h.data?.full) continue;
  const m = h.data.full, cc = h.data.config;
  L.push(`| ${r.combo} | ${h.scenario || '—'} | ${m.files} | ${(m.bytes / 1048576).toFixed(0)} | ${Math.round(m.enumerationDoneMs)} | ${Math.round(m.totalMs)} | ${Math.round(m.timeToFirstProgressMs ?? 0)} | ${m.filesPerSec} | ${m.mibPerSec} | ${m.heapPeakGrowthBytes == null ? 'n/a' : (m.heapPeakGrowthBytes / 1048576).toFixed(1)} | ${m.maxMainThreadLagMs} | ${h.data.cancel?.cancelLatencyMs == null ? '—' : Math.round(h.data.cancel.cancelLatencyMs)} | workers=${cc.poolSize}, chunk=${cc.chunkSize / 1048576}MiB, ${cc.mode}, enum×${cc.enumConcurrency} |`);
}

L.push('', '## Observations (checks without a pass/fail expectation)', '');
for (const id of ['staged-write', 'entries', 'links', 'race', 'handle-persist', 'handle-reload', 'identity-other']) {
  const lines = [];
  for (const r of runs) for (const h of r.history) {
    if (h.id !== id || h.rootKind === 'opfs') continue;
    for (const c of h.checks ?? []) if (c.ok === null) lines.push(`- **${r.combo}**${h.scenario ? ` (${h.scenario})` : ''} — ${c.name}: \`${(c.detail ?? '').slice(0, 400)}\``);
  }
  if (lines.length) L.push(`### ${id}`, '', ...[...new Set(lines)], '');
}

L.push('## Failed checks', '');
const fails = [];
for (const r of runs) for (const h of r.history) {
  if (h.rootKind === 'opfs') continue;
  for (const c of h.checks ?? []) if (c.ok === false) fails.push(`- **${r.combo}** ${h.id}${h.scenario ? ` (${h.scenario})` : ''}: ${c.name}${c.detail ? ` — ${c.detail}` : ''}`);
  if (h.status === 'error') fails.push(`- **${r.combo}** ${h.id}: error ${(h.error ?? '').split('\n')[0]}`);
}
L.push(fails.length ? [...new Set(fails)].join('\n') : 'None recorded.', '');
L.push('## Excluded runs', '', excluded.length ? excluded.join('\n') : 'None.', '');
fs.mkdirSync(path.dirname(values.out), { recursive: true });
fs.writeFileSync(values.out, L.join('\n'));
console.log(`wrote ${values.out}: ${covered.length}/6 combinations, ${runs.length} run file(s)`);
